// Одноразово: структурований текст сторінки «Діяльність» (зміст той самий, виправлено помилки).
// Попередня версія лишається в історії: адмінка → Сторінки → Діяльність → «Версії».
import { getPayload } from 'payload'
import config from '../payload.config'

const payload = await getPayload({ config: await config })

const text = (t: string, format = 0) => ({ type: 'text', text: t, version: 1, detail: 0, format, mode: 'normal', style: '' })
const base = { version: 1, direction: 'ltr', format: '', indent: 0 }
const p = (...children: any[]) => ({ type: 'paragraph', ...base, textFormat: 0, textStyle: '', children })
const h2 = (t: string) => ({ type: 'heading', tag: 'h2', ...base, children: [text(t)] })
const ul = (items: string[]) => ({
  type: 'list', listType: 'bullet', tag: 'ul', start: 1, ...base,
  children: items.map((t, i) => ({ type: 'listitem', value: i + 1, ...base, children: [text(t)] })),
})
let n = 0
const block = (fields: Record<string, unknown>) => ({ type: 'block', version: 2, format: '', fields: { id: `blk${Date.now().toString(36)}${n++}`, blockName: '', ...fields } })
const B = 1 // жирний

const content = {
  root: {
    type: 'root', ...base,
    children: [
      h2('Наша мета'),
      p(
        text('Головна мета діяльності '),
        text('ДНТ «Національна агенція розвитку територій України»', B),
        text(' — реалізація політики з питань тимчасово окупованої території України, захист прав населення, що на ній проживає, та відновлення на цій території конституційного ладу.'),
      ),

      h2('Що ми робимо'),
      block({
        blockType: 'cards',
        items: [
          { icon: 'heart', title: 'Допомога людям', text: 'Надаємо гуманітарну, соціальну, консультаційно-інформаційну, психологічну та іншу допомогу цивільному населенню — зокрема тим, хто перебуває на тимчасово окупованій території України.' },
          { icon: 'phone', title: 'Гарячі лінії', text: 'Обслуговуємо гарячу лінію з кризових питань 1548 і гарячу лінію Уповноваженого з питань ВПО — цілодобово й без вихідних.' },
          { icon: 'home', title: 'Підтримка ВПО', text: 'Розробляємо проєкти, програми й заходи соціального спрямування для внутрішньо переміщених осіб та організовуємо соціальну роботу з ними.' },
          { icon: 'scales', title: 'Міжнародне гуманітарне право', text: 'Реалізуємо заходи, передбачені нормами міжнародного гуманітарного права.' },
        ],
      }),

      h2('Гаряча лінія 1548'),
      p(
        text('У Товаристві працює '),
        text('відділ інформаційно-аналітичного забезпечення «гарячої лінії»', B),
        text('. Він цілодобово, без перерв і вихідних оперативно реагує на звернення громадян з питань внутрішньо переміщених осіб (ВПО).'),
      ),
      block({
        blockType: 'stat',
        number: '2 150 010+',
        label: 'дзвінків громадян опрацьовано',
        note: 'З червня 2022 по квітень 2026 року — консультативна, психологічна та практична допомога людям, які опинилися в скрутному становищі внаслідок збройної агресії проти України. Кількість звернень продовжує зростати.',
      }),

      h2('Соціальна робота з ВПО'),
      p(text('У межах своєї діяльності Товариство:')),
      ul([
        'організовує розробку проєктів, програм і заходів соціального спрямування для підтримки ВПО;',
        'організовує та контролює соціальну роботу з ВПО, зокрема надання соціальних послуг;',
        'виявляє осіб і сім’ї, які перебувають у складних життєвих обставинах внаслідок збройної агресії;',
        'визначає потреби ВПО в соціальних і реабілітаційних послугах та добирає надавачів цих послуг.',
      ]),
    ],
  },
}

const page = (await payload.find({ collection: 'pages', where: { slug: { equals: 'diyalnist' } }, limit: 1, depth: 0 })).docs[0]
if (!page) throw new Error('Сторінку «Діяльність» не знайдено')
await payload.update({ collection: 'pages', id: page.id, locale: 'uk', data: { content, _status: 'published' } as any })
payload.logger.info('Готово: сторінку «Діяльність» оновлено')
process.exit(0)
